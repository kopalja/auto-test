class PipelineTest(Case):
    def test_seeded_bug_produces_minimal_verified_pr(self):
        self.set_plan(investigation=[{**INVESTIGATE_FIX, 'result': {
            'findings': [finding()], 'coverage': [{'area': 'calc.divide', 'status': 'tested', 'notes': 'repro'}]}}],
            fixing=[GOOD_FIX], verification=[GOOD_VERIFY])
        self.assertEqual(self.run_cli('--once'), 0)
        sha = self.head()
        [run] = self.runs()
        self.assertEqual((run['status'], run['sha']), ('completed', sha))
        self.assertEqual(self.state().checkpoint('owner/calc')['sha'], sha)
        [pr] = self.gh.created('pr')
        self.assertTrue(pr['body'].startswith('## 🤖 Generated by Claude\n'))
        for text in (sha, 'bug observed', 'bug not observed', 'Return None for a zero divisor', '<!-- auto-test:f-'):
            self.assertIn(text, pr['body'])
        remote = self.remotes['owner/calc']
        self.assertEqual(git(remote, 'rev-parse', pr['branch'] + '^'), sha)
        self.assertEqual(git(remote, 'diff', '--name-only', sha, pr['branch']).split(), ['calc.py', 'test_zero.py'])
        self.assertEqual(self.gh.created('issue'), [])
        self.assertNotIn(str(self.tmp), pr['body'])  # Evidence excerpts show <run>/..., not host paths.
        self.assertIn('<run>/workspace/calc.py', pr['body'])
        self.assertEqual(git(remote, 'log', '-1', '--format=%s', pr['branch']),
                         'Fix: divide() raises ZeroDivisionError instead of returning None')
        self.assertEqual([c['stage'] for c in self.calls()], ['investigation', 'fixing', 'verification'])
        self.assertIn('Coverage', self.log())
        run_dir = Path(run['directory'])
        self.assertTrue((run_dir / 'run.json').is_file())
        self.assertFalse((run_dir / 'workspace').exists())
        # Unchanged main: skipped without model calls or duplicate reports.
        self.assertEqual(self.run_cli('--once'), 0)
        self.assertEqual(len(self.calls()), 3)
        self.assertEqual(len(self.gh.created()), 1)
        self.assertIn('unchanged', self.log())

