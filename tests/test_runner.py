class BudgetTest(Case):
    def test_soft_budget_is_not_a_hard_kill_and_stops_new_work(self):
        slow = {'actions': [{'do': 'repro'}, {'do': 'sleep', 'seconds': 1.5}],
                'result': {'findings': [finding()], 'worth_continuing': True, 'overrun_reason': 'finishing repro'}}
        self.set_plan(investigation=[slow], fixing=[GOOD_FIX], verification=[{'actions': [{'do': 'verify_issue'}]}])
        self.run_cli('--once', soft_budget_minutes=0.01)
        self.assertEqual(len(self.calls('investigation')), 1)  # No new investigation after the target.
        self.assertEqual(self.calls('fixing'), [])  # No new fix after the target...
        self.assertEqual(len(self.calls('verification')), 1)  # ...but the confirmed finding is verified.
        [issue] = self.gh.created('issue')
        self.assertIn('soft time budget', issue['body'])
        self.assertIn('Soft budget overrun in investigation-1: finishing repro', self.log())
        self.assertEqual(self.runs()[0]['status'], 'completed')

    def test_investigation_continues_while_budget_remains(self):
        self.set_plan(investigation=[{'result': {'worth_continuing': True}}, {'result': {'worth_continuing': False}}])
        self.run_cli('--once')
        rounds = self.calls('investigation')
        self.assertEqual([c['ctx']['round'] for c in rounds], [1, 2])
        budget = rounds[0]['ctx']['budget']
        self.assertEqual(budget['soft_budget_minutes'], 20)
        self.assertTrue(budget['target_finish'].endswith(('+01:00', '+02:00')))
        self.assertLess(budget['stage_target'], budget['target_finish'])


